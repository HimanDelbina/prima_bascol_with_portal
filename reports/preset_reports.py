PRESET_REPORT_ALIASES = {
    "product": "by_product",
    "party": "by_party",
    "driver": "by_driver",
    "discrepancy": "variance_analysis",
}


def get_preset_report_by_code(code: str):
    code = PRESET_REPORT_ALIASES.get(code, code)
    for r in PRESET_REPORTS:
        if r["code"] == code:
            return r
    return None

def get_preset_report_by_id(report_id: int):
    for r in PRESET_REPORTS:
        if r["id"] == report_id:
            return r
    return None
